"""T-05 (part 2): export a landmark fixture for cross-validating symmetry.js.

The geometric channel is implemented twice on purpose:
  - Python: train/derive_mirror_pairs.py (derivation + calibration)
  - JS:     web/src/core/symmetry.js  (what actually runs on the phone)

If the two disagree, one of them is wrong. This script dumps real landmark sets
together with the Python-computed asymmetry, so the JS unit test can assert they
match to 1e-6.

Run: .venv\\Scripts\\python.exe train\\export_landmark_fixture.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.stdout.reconfigure(encoding="utf-8")

APP = Path(__file__).resolve().parents[1]
FACES = APP / "work" / "cleaned" / "faces" / "NonStroke"
TASK = APP / "web" / "public" / "mediapipe" / "face_landmarker.task"
REPORTS = APP / "work" / "reports"
FIXTURE = APP / "web" / "tests" / "fixtures" / "landmarks_sample.json"

N = 12
YAW_TOL = 0.15
IDX = {"eye_r_outer": 33, "eye_l_outer": 263, "nasion": 168, "chin": 152, "nose_tip": 1}


def align(pts: np.ndarray):
    """Canonical frame: origin = eye midpoint, scale = inter-ocular,
    rotation = MIDLINE (nasion -> chin) vertical. Must match symmetry.js."""
    r, l = pts[IDX["eye_r_outer"]], pts[IDX["eye_l_outer"]]
    mid = (r + l) / 2.0
    # 2D inter-ocular distance, identical to symmetry.js align()
    scale = float(np.linalg.norm((l - r)[:2]))
    if scale < 1e-6:
        return None
    a, b = pts[IDX["nasion"]], pts[IDX["chin"]]
    v = b[:2] - a[:2]
    vlen = np.linalg.norm(v)
    if vlen < 1e-9:
        return None
    vx, vy = v / vlen
    xy = (pts[:, :2] - mid[:2]) / scale
    return np.stack([vy * xy[:, 0] - vx * xy[:, 1],
                     vx * xy[:, 0] + vy * xy[:, 1]], axis=1)


def yaw_proxy(xy: np.ndarray) -> float:
    n = xy[IDX["nose_tip"]]
    return float(abs(np.linalg.norm(n - xy[IDX["eye_r_outer"]])
                     - np.linalg.norm(n - xy[IDX["eye_l_outer"]])))


def mirror_pt(p: np.ndarray, a: np.ndarray, b: np.ndarray) -> np.ndarray:
    ab = b - a
    t = float(np.dot(p - a, ab) / np.dot(ab, ab))
    return 2.0 * (a + t * ab) - p


def main() -> int:
    import mediapipe as mp
    from mediapipe.tasks import python as mp_python
    from mediapipe.tasks.python import vision

    pairs = json.loads((REPORTS / "mirror_pairs.json").read_text(encoding="utf-8"))
    pairs_flat = pairs["pairs_flat"]
    zones = pairs["pairs"]
    axis = pairs["axis"]

    landmarker = vision.FaceLandmarker.create_from_options(
        vision.FaceLandmarkerOptions(
            base_options=mp_python.BaseOptions(model_asset_path=str(TASK)),
            output_face_blendshapes=False,
            output_facial_transformation_matrixes=False,
            num_faces=1,
            running_mode=vision.RunningMode.IMAGE,
        )
    )

    files = sorted(FACES.glob("*.jpg"))
    step = max(1, len(files) // 200)
    samples = []
    for p in files[::step]:
        if len(samples) >= N:
            break
        try:
            res = landmarker.detect(mp.Image.create_from_file(str(p)))
            if not res.face_landmarks:
                continue
            pts = np.array([[q.x, q.y, q.z] for q in res.face_landmarks[0]], dtype=np.float64)
            if pts.shape[0] < 478:
                continue
            xy = align(pts)
            if xy is None or yaw_proxy(xy) >= YAW_TOL:
                continue

            a_pt, b_pt = xy[axis[0]], xy[axis[1]]
            mirrored = np.array([mirror_pt(p, a_pt, b_pt) for p in xy])

            # v2 metric: mirror error (captures horizontal AND vertical droop)
            zone_vals = {z: float(np.mean([np.linalg.norm(mirrored[i] - xy[j]) for i, j in pl]))
                         for z, pl in zones.items() if pl}
            a_val = float(np.mean([zone_vals[z] for z in
                                   ("forehead", "eyelid", "nasolabial", "mouth") if z in zone_vals]))

            # also store a synthesised perfectly symmetric variant + a drooped variant
            samples.append({
                "file": p.name,
                "landmarks": [[round(float(q.x), 7), round(float(q.y), 7), round(float(q.z), 7)]
                              for q in res.face_landmarks[0]],
                "python": {"a": a_val, "zones": {k: float(v) for k, v in zone_vals.items()}},
            })
        except Exception:  # noqa: BLE001
            continue

    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(json.dumps({
        "note": "cross-validation fixture for web/tests/symmetry.test.js; generated by train/export_landmark_fixture.py",
        "axis": axis,
        "anchors": IDX,
        "samples": samples,
    }, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"[written] {FIXTURE}  ({len(samples)} samples)")
    if samples:
        a_vals = [s["python"]["a"] for s in samples]
        print(f"  python A: min={min(a_vals):.4f} median={np.median(a_vals):.4f} max={max(a_vals):.4f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
